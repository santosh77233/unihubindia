export const getAllColleges = (): College[] => {
  return westBengalColleges.flatMap((cat) => cat.colleges)
}

export const searchColleges = (query: string): College[] => {
  if (!query.trim()) return getAllColleges()
  const lowerQuery = query.toLowerCase()
  return getAllColleges().filter(
    (college) =>
      college.name.toLowerCase().includes(lowerQuery) ||
      college.location.toLowerCase().includes(lowerQuery) ||
      college.code.toLowerCase().includes(lowerQuery)
  )
}
